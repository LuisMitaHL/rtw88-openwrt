#!/bin/bash
#
# OpenWrt 24.10 compat generator for the rtw88 driver.
#
# Run this inside the top-level rtw88 tree (the directory with main.h,
# usb.c, ...) after applying every 0xxx-*.patch from the rtw88-openwrt repo
# and staging the result with `git add -A`; the rewrites are left unstaged
# so `git diff > 999-openwrt-24.10-compat.patch` picks them up.
#
# A LINUX_VERSION_CODE check is rewritten when its threshold falls inside
# [OPENWRT kernel, backport API]: on OpenWrt the kernel plus the mac80211
# backports already provide those branches, so the newer code must be
# selected regardless of the kernel version:
#
#   <  KERNEL_VERSION() -> ... && !defined(OPENWRT)
#   >= KERNEL_VERSION() -> ... || defined(OPENWRT)
#
# Thresholds below the OpenWrt kernel need no guard (the OpenWrt kernel is
# newer), and thresholds above the backport API must stay (that code does
# not exist in the backport; e.g. the 7.0 alloc_obj API). Files in
# SKIP_FILES are left untouched entirely (API missing from the backport).
#
# Rewrites are end-of-line anchored, so lines that already carry a guard
# no longer match: running twice changes nothing. #if and #elif get equal
# treatment. Only whole-line directives of the exact spellings above go
# through the rewrite; anything else (extra conditions, other operators,
# continued lines) is reported and left for manual handling.
#
# A rewrite can only act on a check someone wrote. Calls upstream makes
# with no check around them, though the release's kernel has no such API,
# are listed in UNGUARDED_CALLS and get the guard this script would have
# generated for them.
#
# Generated by tools/rtw88-patcher-sync.sh from
# tools/rtw88-patcher-openwrt.template.sh: edit those, not this file.

set -u

# ------------------------------------------------------------- configuration

# Linux version of the OpenWrt kernels for this release.
OPENWRT_KERNEL='6.6'
# mac80211 backport level bundled into those kernels.
BACKPORT_API='6.11'
# Files never rewritten, single-space separated.
SKIP_FILES='usb.c usb.h'
# Line in main.h immediately before which '#define OPENWRT' is inserted.
DEFINE_ANCHOR='#if LINUX_VERSION_CODE < KERNEL_VERSION(6, 12, 0)'
# Calls to guard that upstream makes unconditionally, one rule per line:
#
#   file|function|occurrence|kernel-version|old-call|new-call
#
# file and function locate the call, occurrence picks the nth match in
# that function (1 unless it calls the same thing twice), old-call must
# appear on the call's own line and becomes
#
#   #if LINUX_VERSION_CODE >= KERNEL_VERSION(kernel-version)
#   <old-call, copied from the source byte for byte>
#   #else
#   new-call
#   #endif
#
# when the release's kernel predates kernel-version (the version the call
# came in with); a newer kernel keeps the call untouched. A rule that
# finds no call in its file is an error, never silence.
UNGUARDED_CALLS='tx.c|rtw_tx_report_purge_timer|1|6.16.0|timer_container_of(rtwdev, t,|from_timer(rtwdev, t, tx_report.purge_timer);'

# ------------------------------------------------------------------ helpers

verbose=0
if [ "${1:-}" = "-v" ]; then
	verbose=1
fi

log() { if [ "$verbose" -eq 1 ]; then printf '%s\n' "$*"; fi; }
warn() { printf 'WARN: %s\n' "$*" >&2; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

version_code() { # '5.15' | 'a, b, c' -> numeric version code
	local a b c
	IFS=',. ' read -r a b c <<<"$1"
	c=${c:-0}
	echo $((10#$a * 65536 + 10#$b * 256 + 10#$c))
}

code_openwrt=$(version_code "$OPENWRT_KERNEL")
code_backport=$(version_code "$BACKPORT_API")
if [ "$code_openwrt" -gt "$code_backport" ]; then
	die "OPENWRT_KERNEL ($OPENWRT_KERNEL) exceeds BACKPORT_API ($BACKPORT_API)"
fi

# ---------------------------------------------------------- tree enumeration

src_files() { # every top-level .c/.h, minus vendored code and SKIP_FILES
	find . -type d -name alt_rtl8821ce -prune -o \
		\( -type f -name '*.c' -o -type f -name '*.h' \) -print
}

skip_file() { # path -> 0 when policy says the file must not be rewritten
	local file=${1#./} skip
	[ "${file%/*}" = "$file" ] || return 1 # top level only
	for skip in $SKIP_FILES; do
		[ "$file" = "$skip" ] && return 0
	done
	return 1
}

# main.h: insert '#define OPENWRT' plus a blank line immediately before the
# DEFINE_ANCHOR line, so it is visible to every rewritten check below (main.h
# is pulled in first by all of them). The unique-match assertion guards
# against upstream drift; refusing to guess is better than a misplaced edit.
insert_define() {
	if grep -q '^#define OPENWRT$' main.h; then
		log "main.h: #define OPENWRT already present"
		return
	fi
	local count
	count=$(grep -c "^${DEFINE_ANCHOR}\$" main.h || :)
	if [ "$count" -ne 1 ]; then
		die "main.h: expected exactly one '${DEFINE_ANCHOR}' line, found $count"
	fi
	sed -i "/^${DEFINE_ANCHOR}\$/i\\
#define OPENWRT\\
\\
" main.h
	log "main.h: inserted #define OPENWRT"
}

# ------------------------------------------------------------ threshold scan

# Numeric version codes of every KERNEL_VERSION(a, b, c) in the tree,
# restricted to [code_openwrt, code_backport]: thresholds outside that
# window either already behave identically on OpenWrt or select code the
# backport does not provide, so they stay untouched.
threshold_codes() { # -> distinct numeric codes, stdin: file paths
	grep -hoE 'KERNEL_VERSION\([0-9]+, *[0-9]+, *[0-9]+\)' "$@" |
	tr -d ' ' | sort -u | sed 's/^KERNEL_VERSION(//; s/)$//' |
	while IFS= read -r nums; do
		case $nums in
			'') continue;;
		esac
		code=$(version_code "$nums")
		if [ "$code" -ge "$code_openwrt" ] &&
			[ "$code" -le "$code_backport" ]; then
			printf '%s\n' "$code"
		fi
	done
}

# ------------------------------------------------------------ rewrite engine

# One expression per (spelling, operator) per threshold, as sed -e script.
# The trailing $ anchor makes guarded lines unmatched, so rewrites are
# idempotent; the '&' in the replacement reproduces the source spacing.
# '&' and '|' in the replacement are escaped for sed ('&&' would otherwise
# expand to the whole match).
sed_exprs() { # integer version codes as args
	local a b code
	for code in "$@"; do
		a=$((code / 65536))
		b=$((code / 256 % 256))
		printf 's@^[[:space:]]*#(el)?if[[:space:]]+LINUX_VERSION_CODE[[:space:]]*<[[:space:]]*KERNEL_VERSION\\([[:space:]]*%d, *%d, *[0-9]+\\)$@& \\&\\& !defined(OPENWRT)@\n' "$a" "$b"
		printf 's@^[[:space:]]*#(el)?if[[:space:]]+\\(LINUX_VERSION_CODE[[:space:]]*<[[:space:]]*KERNEL_VERSION\\([[:space:]]*%d, *%d, *[0-9]+\\)\\)$@& \\&\\& !defined(OPENWRT)@\n' "$a" "$b"
		printf 's@^[[:space:]]*#(el)?if[[:space:]]+LINUX_VERSION_CODE[[:space:]]*>=[[:space:]]*KERNEL_VERSION\\([[:space:]]*%d, *%d, *[0-9]+\\)$@& || defined(OPENWRT)@\n' "$a" "$b"
		printf 's@^[[:space:]]*#(el)?if[[:space:]]+\\(LINUX_VERSION_CODE[[:space:]]*>=[[:space:]]*KERNEL_VERSION\\([[:space:]]*%d, *%d, *[0-9]+\\)\\)$@& || defined(OPENWRT)@\n' "$a" "$b"
	done
}

# ------------------------------------------------------- unguarded call table

# How to find the end of the function a rule names. The anchor that opens
# each function is a property of upstream's formatting, not of this tool,
# hence a table; only functions named in UNGUARDED_CALLS need a row.
#
#   F <name> <regex>   a definition starting in column 1
#   N <name> <regex>   the #if half of a conditionally defined function
#   I <name> <regex>   a definition nested in such a half
#
# The 6.16 timer commit replaced one function with another rather than
# adding a block, so both halves are definitions: a release whose kernel
# predates 6.16 compiles the old signature and needs the guard in the body
# the old signature owns. A body ends at the first column-1 line after it
# (F) or at the #else: of its block (N, I). An anchor that matches nothing
# is a stale row and an error.
FUNC_ANCHORS='
F rtw_usb_tx_agg_skb ^static bool rtw_usb_tx_agg_skb\(
N rtw_usb_tx_queue_purge ^#if LINUX_VERSION_CODE >= KERNEL_VERSION\(6, 13, 0\)
I rtw_usb_tx_queue_purge rtw_usb_tx_queue_purge
I rtw_tx_report_purge_timer ^void rtw_tx_report_purge_timer\(void \*cntx\)
'

# file name -> first and last line of that function's body.
func_body() { # file name -> "start end"
	local file=$1 name=$2 kind fname regex start= end=
	while read -r kind fname regex; do
		[ "$fname" = "$name" ] || continue
		start=$(grep -nE -- "$regex" "$file" | sed -n '1s/:.*//p') || :
		[ -n "$start" ] ||
			die "$file: $name not found; FUNC_ANCHORS has no matching row"
		case $kind in
		F) end=$(awk -v s="$start" 'NR > s && /^[^[:space:]]/ { print NR - 1; exit }' "$file");;
		N|I) end=$(awk -v s="$start" 'NR > s && /^#else$/ { print NR - 1; exit }' "$file");;
		*) die "$file: unknown anchor kind '$kind' for $name";;
		esac
		[ -n "$end" ] || die "$file: cannot find the end of $name"
		printf '%s %s\n' "$start" "$end"
		return 0
	done <<<"$FUNC_ANCHORS"
	die "$name is in UNGUARDED_CALLS but has no FUNC_ANCHORS row"
}

# Rewrite the call a rule names into the guard a LINUX_VERSION_CODE check
# would have produced. The #if goes in at the call's indentation and the call
# itself is copied from the source verbatim, so tabs and line wrapping stay
# byte-identical: a patch's context lines have to match the tree exactly.
apply_call_rules() { # file -> 0 when something was rewritten
	local file=$1 rules rule n=0
	local func occ ver old new start end ln
	[ -n "$UNGUARDED_CALLS" ] || return 1
	rules=$(printf '%s\n' "$UNGUARDED_CALLS" | grep -F "$file|" || :)
	[ -n "$rules" ] || return 1
	while IFS= read -r rule; do
		IFS='|' read -r func occ ver old new <<<"$rule"
		read -r start end < <(func_body "$file" "$func")
		ln=$(awk -v s="$start" -v e="$end" -v o="$occ" -v c="$old" \
			'NR >= s && NR <= e && index($0, c) && ++k == o { print NR; exit }' "$file") || :
		if [ -z "$ln" ]; then
			warn "$file: no '$old' #$occ in $func; UNGUARDED_CALLS row stale?"
			continue
		fi
		if [ "$code_openwrt" -ge "$(version_code "$ver")" ]; then
			log "$file:$ln: $old is in kernel $OPENWRT_KERNEL"
			continue
		fi
		sed -i "${ln}s@^\([[:space:]]*\).*\$@\\
#if LINUX_VERSION_CODE >= KERNEL_VERSION($ver)\\
&\\
#else\\
\1$new\\
#endif@" "$file"
		log "guarded: $file:$ln ($old -> $new)"
		n=$((n + 1))
	done <<<"$rules"
	[ "$n" -gt 0 ]
}

# ---------------------------------------------------------------- processing

apply_rewrites() { # file prog
	sed -E -i -f "$2" "$1"
}

# In-range checks left without a guard: anything the rewrites do not
# recognise (extra conditions, other operators, continued lines) would
# silently keep the kernel-version branch on OpenWrt.
warn_unguarded() { # file paths as args
	local file hit triple vc inr
	for file in "$@"; do
		skip_file "$file" && continue
		if ! grep -nE '^[[:space:]]*#[[:space:]]*(el)?if' "$file" |
			grep -F 'KERNEL_VERSION(' |
			grep -qv 'defined(OPENWRT)'; then
			continue
		fi
		while IFS= read -r hit; do
			inr=
			while IFS= read -r triple; do
				triple=${triple#KERNEL_VERSION(}
				triple=${triple%)}
				triple=${triple%%[!0-9, -]*}
				vc=$(version_code "$triple")
				if [ "$vc" -ge "$code_openwrt" ] &&
					[ "$vc" -le "$code_backport" ]; then
					inr=1
					break
				fi
			done < <(grep -oE 'KERNEL_VERSION\([0-9]+, *[0-9]+, *[0-9]+\)' <<<"$hit")
			if [ -n "$inr" ]; then
				warn "in-range check left unguarded: $file:${hit%%:*}: ${hit#*:}"
			fi
		done < <(grep -nE '^[[:space:]]*#[[:space:]]*(el)?if' "$file" |
			grep -F 'KERNEL_VERSION(' |
			grep -v 'defined(OPENWRT)')
	done
}

main() {
	local codes file total=0 nfile=0
	[ -f main.h ] ||
		die "main.h not found; run from the top level of the rtw88 tree"
	insert_define

	prog=$(mktemp)
	# shellcheck disable=SC2046 # newline-separated paths, no spaces
	mapfile -t codes < <(threshold_codes $(src_files))
	if [ "${#codes[@]}" -eq 0 ]; then
		warn "no in-range KERNEL_VERSION thresholds found"
	else
		sed_exprs "${codes[@]}" > "$prog"
	fi

	for file in $(src_files); do
		total=$((total + 1))
		skip_file "$file" && continue
		if [ "${#codes[@]}" -ne 0 ] && grep -q 'KERNEL_VERSION(' "$file"; then
			apply_rewrites "$file" "$prog" && log "rewrote: $file"
			nfile=$((nfile + 1))
		fi
		apply_call_rules "$file" && { log "guarded on request: $file"; nfile=$((nfile + 1)); }
	done
	log "files scanned: $total, rewritten: $nfile"

	# shellcheck disable=SC2046 # newline-separated paths, no spaces
	warn_unguarded $(src_files)
}

prog=
trap 'rm -f "$prog"' EXIT

main "$@"
